"""PostgreSQL database access for alerts, blocked IPs, whitelist, and models.

Ứng dụng chỉ dùng PostgreSQL. Nếu không kết nối được, hệ thống báo lỗi rõ ràng
thay vì âm thầm chuyển sang một CSDL khác.
"""

from __future__ import annotations

import json
import logging
import os
from contextlib import contextmanager
from datetime import datetime
from typing import Any, Generator

try:
    import psycopg2
    from psycopg2.extras import RealDictCursor
except ImportError as exc:
    raise RuntimeError(
        "PostgreSQL driver is required; install dependencies with "
        "`python -m pip install -r requirements.txt`."
    ) from exc

logger = logging.getLogger("AI_IDS.DB")

_database_config: dict[str, Any] = {}


class _Connection:
    """Small adapter preserving the existing conn.execute call pattern."""

    def __init__(self, connection):
        self._connection = connection

    def execute(self, query: str, params: tuple[Any, ...] | None = None):
        cursor = self._connection.cursor(cursor_factory=RealDictCursor)
        cursor.execute(query, params or ())
        return cursor

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()


def _connection_parameters() -> dict[str, Any]:
    dsn = os.environ.get("DATABASE_URL") or _database_config.get("dsn")
    if dsn:
        return {"dsn": dsn}
    return {
        "host": _database_config.get("host", "127.0.0.1"),
        "port": int(_database_config.get("port", 5432)),
        "dbname": _database_config.get("dbname", "ids_system"),
        "user": _database_config.get("user", "ids_user"),
        "password": os.environ.get(
            "POSTGRES_PASSWORD", _database_config.get("password", "")
        ),
        "connect_timeout": int(_database_config.get("connect_timeout", 5)),
    }


def _now_iso() -> str:
    """Thời điểm hiện tại dạng ISO, dùng để so sánh chuỗi `expires_at`."""
    return datetime.now().isoformat()


@contextmanager
def get_db_connection() -> Generator[_Connection, None, None]:
    """Open a PostgreSQL connection and commit or roll back one operation."""
    params = _connection_parameters()
    try:
        connection = psycopg2.connect(**params)
    except Exception as ex:
        target = (
            "DATABASE_URL"
            if "dsn" in params
            else f"{params.get('host')}:{params.get('port')}/{params.get('dbname')}"
        )
        logger.error("Không thể kết nối PostgreSQL tại %s: %s", target, ex)
        raise

    wrapped = _Connection(connection)
    try:
        yield wrapped
        wrapped.commit()
    except Exception:
        wrapped.rollback()
        logger.exception("Lỗi giao dịch PostgreSQL")
        raise
    finally:
        wrapped.close()


def init_db(database_config: dict[str, Any] | None = None) -> None:
    """Configure PostgreSQL and create the application schema if necessary.

    Ném lỗi nếu không kết nối được PostgreSQL để tránh ghi nhầm sang CSDL khác.
    """
    global _database_config
    if database_config is not None:
        _database_config = dict(database_config)

    schema_statements = (
        """
        CREATE TABLE IF NOT EXISTS alerts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ts TEXT NOT NULL,
            src_ip TEXT NOT NULL,
            dest_ip VARCHAR(64),
            attack_type TEXT NOT NULL,
            score DOUBLE PRECISION NOT NULL,
            severity TEXT NOT NULL,
            status TEXT NOT NULL,
            decided_by TEXT,
            decided_at TEXT,
            alert_timestamp TIMESTAMPTZ DEFAULT now(),
            source_of_detection VARCHAR(50) DEFAULT 'Hybrid_Ensemble',
            confidence DOUBLE PRECISION DEFAULT 1.0,
            evidence JSONB
        )
        """,
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS dest_ip VARCHAR(64)",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS alert_timestamp TIMESTAMPTZ DEFAULT now()",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS source_of_detection VARCHAR(50) DEFAULT 'Hybrid_Ensemble'",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS confidence DOUBLE PRECISION DEFAULT 1.0",
        "ALTER TABLE alerts ADD COLUMN IF NOT EXISTS evidence JSONB",
        """
        CREATE TABLE IF NOT EXISTS blocked_ips (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ip TEXT NOT NULL UNIQUE,
            blocked_at TEXT NOT NULL,
            expires_at TEXT,
            reason TEXT,
            alert_id BIGINT REFERENCES alerts(id),
            method TEXT,
            unblocked_at TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS whitelist (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ip TEXT NOT NULL UNIQUE,
            note TEXT,
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS models (
            version TEXT PRIMARY KEY,
            algorithm TEXT NOT NULL,
            trained_at TEXT NOT NULL,
            f1 DOUBLE PRECISION NOT NULL,
            fpr DOUBLE PRECISION NOT NULL,
            path TEXT NOT NULL,
            is_active SMALLINT NOT NULL DEFAULT 0
        )
        """,
        "CREATE INDEX IF NOT EXISTS idx_alerts_ip ON alerts(src_ip)",
        "CREATE INDEX IF NOT EXISTS idx_alerts_status ON alerts(status)",
        "CREATE INDEX IF NOT EXISTS idx_blocked_ip ON blocked_ips(ip)",
        "CREATE INDEX IF NOT EXISTS idx_whitelist_ip ON whitelist(ip)",
    )
    with get_db_connection() as conn:
        for statement in schema_statements:
            conn.execute(statement)
    target = (
        "DATABASE_URL"
        if os.environ.get("DATABASE_URL") or _database_config.get("dsn")
        else f"{_database_config.get('host', '127.0.0.1')}:{_database_config.get('port', 5432)}/{_database_config.get('dbname', 'ids_system')}"
    )
    logger.info("Đã khởi tạo schema PostgreSQL tại %s", target)


def add_alert(
    src_ip: str,
    attack_type: str,
    score: float,
    severity: str,
    status: str = "pending",
    decided_by: str | None = None,
    decided_at: str | None = None,
    ts: str | None = None,
    dest_ip: str | None = None,
    source_of_detection: str | None = None,
    confidence: float | None = None,
    evidence: Any = None,
    alert_timestamp: datetime | None = None,
) -> int:
    """Add an alert and return its database ID.

    Các trường ``dest_ip``/``source_of_detection``/``confidence``/``evidence`` là
    phần mở rộng phục vụ dashboard và hồ sơ bằng chứng của AI Worker.
    """
    now_str = ts or datetime.now().isoformat()
    evidence_json = (
        json.dumps(evidence, default=str)
        if evidence is not None and not isinstance(evidence, str)
        else evidence
    )
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            INSERT INTO alerts
                (ts, src_ip, dest_ip, attack_type, score, severity, status,
                 decided_by, decided_at, alert_timestamp, source_of_detection,
                 confidence, evidence)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            """,
            (
                now_str,
                src_ip,
                dest_ip,
                attack_type,
                score,
                severity,
                status,
                decided_by,
                decided_at,
                alert_timestamp or datetime.now(),
                source_of_detection or "AI_Engine",
                float(confidence if confidence is not None else score),
                evidence_json,
            ),
        )
        return int(cursor.fetchone()["id"])


def update_alert_status(
    alert_id: int,
    status: str,
    decided_by: str,
    decided_at: str | None = None,
) -> bool:
    now_str = decided_at or datetime.now().isoformat()
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            UPDATE alerts
            SET status = %s, decided_by = %s, decided_at = %s
            WHERE id = %s
            """,
            (status, decided_by, now_str, alert_id),
        )
        return cursor.rowcount > 0


def get_alerts(
    limit: int = 50,
    status: str | None = None,
    since: str | None = None,
) -> list[dict[str, Any]]:
    """Lấy cảnh báo mới nhất.

    ``since`` là mốc thời gian ISO (ví dụ thời điểm app khởi động). Khi truyền
    vào, chỉ cảnh báo phát sinh từ mốc đó trở đi được trả về — nhờ vậy dashboard
    không hiển thị lại các cảnh báo cũ đã lưu trong PostgreSQL từ lần chạy trước.
    """
    clauses: list[str] = []
    params: list[Any] = []
    if status:
        clauses.append("status = %s")
        params.append(status)
    if since:
        clauses.append("ts >= %s")
        params.append(since)

    where = f" WHERE {' AND '.join(clauses)}" if clauses else ""
    params.append(limit)
    with get_db_connection() as conn:
        cursor = conn.execute(
            f"SELECT * FROM alerts{where} ORDER BY id DESC LIMIT %s",
            tuple(params),
        )
        return [dict(row) for row in cursor.fetchall()]


def get_alert_by_id(alert_id: int) -> dict[str, Any] | None:
    with get_db_connection() as conn:
        cursor = conn.execute("SELECT * FROM alerts WHERE id = %s", (alert_id,))
        row = cursor.fetchone()
        return dict(row) if row else None


def add_blocked_ip(
    ip: str,
    reason: str,
    alert_id: int | None = None,
    duration_minutes: int = 60,
    method: str = "ufw",
) -> int:
    now = datetime.now()
    blocked_at = now.isoformat()
    expires_at = datetime.fromtimestamp(
        now.timestamp() + duration_minutes * 60
    ).isoformat()
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            INSERT INTO blocked_ips
                (ip, blocked_at, expires_at, reason, alert_id, method, unblocked_at)
            VALUES (%s, %s, %s, %s, %s, %s, NULL)
            ON CONFLICT(ip) DO UPDATE SET
                blocked_at = EXCLUDED.blocked_at,
                expires_at = EXCLUDED.expires_at,
                reason = EXCLUDED.reason,
                alert_id = EXCLUDED.alert_id,
                method = EXCLUDED.method,
                unblocked_at = NULL
            RETURNING id
            """,
            (ip, blocked_at, expires_at, reason, alert_id, method),
        )
        return int(cursor.fetchone()["id"])


def unblock_ip_record(ip: str) -> bool:
    now_str = datetime.now().isoformat()
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            UPDATE blocked_ips SET unblocked_at = %s
            WHERE ip = %s AND unblocked_at IS NULL
            """,
            (now_str, ip),
        )
        return cursor.rowcount > 0


def get_blocked_ips(active_only: bool = True) -> list[dict[str, Any]]:
    """Danh sách IP bị chặn.

    Khi ``active_only=True`` chỉ trả về các bản ghi chưa gỡ chặn **và chưa hết hạn**.
    """
    with get_db_connection() as conn:
        if active_only:
            cursor = conn.execute(
                """
                SELECT * FROM blocked_ips
                WHERE unblocked_at IS NULL
                  AND (expires_at IS NULL OR expires_at > %s)
                ORDER BY id DESC
                """,
                (_now_iso(),),
            )
        else:
            cursor = conn.execute("SELECT * FROM blocked_ips ORDER BY id DESC")
        return [dict(row) for row in cursor.fetchall()]


def is_ip_blocked(ip: str) -> bool:
    """True nếu IP đang bị chặn và chưa hết hạn."""
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            SELECT id FROM blocked_ips
            WHERE ip = %s
              AND unblocked_at IS NULL
              AND (expires_at IS NULL OR expires_at > %s)
            LIMIT 1
            """,
            (ip, _now_iso()),
        )
        return cursor.fetchone() is not None


def purge_expired_blocks() -> list[str]:
    """Đánh dấu đã gỡ chặn cho các IP quá hạn và trả về danh sách IP đó.

    Dùng để dọn dẹp định kỳ; việc xử lý rule tường lửa (UFW) do lớp Blocker đảm nhiệm.
    """
    now_str = _now_iso()
    with get_db_connection() as conn:
        cursor = conn.execute(
            """
            UPDATE blocked_ips SET unblocked_at = %s
            WHERE unblocked_at IS NULL
              AND expires_at IS NOT NULL
              AND expires_at <= %s
            RETURNING ip
            """,
            (now_str, now_str),
        )
        return [row["ip"] for row in cursor.fetchall()]


def add_to_whitelist(ip: str, note: str = "Thêm bởi quản trị viên") -> bool:
    now_str = datetime.now().isoformat()
    with get_db_connection() as conn:
        conn.execute(
            """
            INSERT INTO whitelist (ip, note, created_at)
            VALUES (%s, %s, %s)
            ON CONFLICT(ip) DO UPDATE SET note = EXCLUDED.note
            """,
            (ip, note, now_str),
        )
    return True


def remove_from_whitelist(ip: str) -> bool:
    with get_db_connection() as conn:
        cursor = conn.execute("DELETE FROM whitelist WHERE ip = %s", (ip,))
        return cursor.rowcount > 0


def get_whitelist() -> list[dict[str, Any]]:
    with get_db_connection() as conn:
        cursor = conn.execute("SELECT * FROM whitelist ORDER BY id ASC")
        return [dict(row) for row in cursor.fetchall()]


def is_in_whitelist(ip: str) -> bool:
    with get_db_connection() as conn:
        cursor = conn.execute(
            "SELECT id FROM whitelist WHERE ip = %s LIMIT 1", (ip,)
        )
        return cursor.fetchone() is not None


def save_model_meta(
    version: str,
    algorithm: str,
    trained_at: str,
    f1: float,
    fpr: float,
    path: str,
    is_active: int = 1,
) -> None:
    with get_db_connection() as conn:
        if is_active:
            conn.execute("UPDATE models SET is_active = 0")
        conn.execute(
            """
            INSERT INTO models
                (version, algorithm, trained_at, f1, fpr, path, is_active)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT(version) DO UPDATE SET
                algorithm = EXCLUDED.algorithm,
                trained_at = EXCLUDED.trained_at,
                f1 = EXCLUDED.f1,
                fpr = EXCLUDED.fpr,
                path = EXCLUDED.path,
                is_active = EXCLUDED.is_active
            """,
            (version, algorithm, trained_at, f1, fpr, path, is_active),
        )


def get_active_model() -> dict[str, Any] | None:
    with get_db_connection() as conn:
        cursor = conn.execute(
            "SELECT * FROM models WHERE is_active = 1 LIMIT 1"
        )
        row = cursor.fetchone()
        return dict(row) if row else None


def clear_alerts() -> int:
    """Xoá toàn bộ cảnh báo (dùng để dọn các cảnh báo giả trước đó).

    Gỡ tham chiếu ``alert_id`` trong bảng blocked_ips trước để không vi phạm khoá ngoại.
    """
    with get_db_connection() as conn:
        conn.execute("UPDATE blocked_ips SET alert_id = NULL WHERE alert_id IS NOT NULL")
        cursor = conn.execute("DELETE FROM alerts")
        return cursor.rowcount


def get_stats(since: str | None = None) -> dict[str, Any]:
    """Thống kê cảnh báo.

    ``since`` giới hạn thống kê trong khoảng thời gian từ mốc ISO trở đi, dùng
    để các biểu đồ không cộng dồn cảnh báo cũ của những lần chạy trước.
    """
    alert_filter = ""
    alert_params: tuple[Any, ...] = ()
    if since:
        alert_filter = " WHERE ts >= %s"
        alert_params = (since,)

    with get_db_connection() as conn:
        cursor = conn.execute(
            f"SELECT attack_type, COUNT(*) AS count FROM alerts{alert_filter} "
            "GROUP BY attack_type",
            alert_params,
        )
        type_counts = {row["attack_type"]: row["count"] for row in cursor.fetchall()}

        cursor = conn.execute(
            f"SELECT status, COUNT(*) AS count FROM alerts{alert_filter} "
            "GROUP BY status",
            alert_params,
        )
        status_counts = {row["status"]: row["count"] for row in cursor.fetchall()}

        cursor = conn.execute(
            """
            SELECT COUNT(*) AS count FROM blocked_ips
            WHERE unblocked_at IS NULL
              AND (expires_at IS NULL OR expires_at > %s)
            """,
            (_now_iso(),),
        )
        active_blocked_count = cursor.fetchone()["count"]

        cursor = conn.execute(
            f"""
            SELECT substring(ts FROM 1 FOR 13) AS hour_slot, COUNT(*) AS count
            FROM alerts{alert_filter}
            GROUP BY hour_slot
            ORDER BY hour_slot DESC
            LIMIT 10
            """,
            alert_params,
        )
        time_series = [
            {"time": row["hour_slot"], "count": row["count"]}
            for row in cursor.fetchall()
        ]
        return {
            "by_type": type_counts,
            "by_status": status_counts,
            "active_blocked_count": active_blocked_count,
            "time_series": time_series,
        }
